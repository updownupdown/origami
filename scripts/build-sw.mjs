// Writes dist/sw.js: precaches the app shell and search index, caches models on demand.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';

const dist = path.resolve('dist');
const base = '/origami/';
const files = [];
const walk = (d) => {
  for (const e of fs.readdirSync(d, { withFileTypes: true })) {
    const p = path.join(d, e.name);
    if (e.isDirectory()) walk(p); else files.push(path.relative(dist, p).split(path.sep).join('/'));
  }
};
walk(dist);
const shell = files.filter((f) =>
  f === 'index.html' || f === 'about/index.html' || f === 'search.json' || f === 'manifest.webmanifest' ||
  f.startsWith('_astro/') || f.startsWith('icon') || f.endsWith('.woff2') && f.includes('latin'));
const hash = crypto.createHash('sha1');
for (const f of shell) hash.update(fs.readFileSync(path.join(dist, f)));
const version = hash.digest('hex').slice(0, 10);
const sw = `// Generated by scripts/build-sw.mjs
const VERSION = '${version}';
const SHELL = 'shell-' + VERSION;
const RUNTIME = 'runtime-v1';
const BASE = '${base}';
const PRECACHE = ${JSON.stringify(shell.map((f) => base + f.replace(/index\.html$/, '')))};

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(SHELL).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith('shell-') && k !== SHELL).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', (e) => {
  const url = new URL(e.request.url);
  if (e.request.method !== 'GET' || url.origin !== location.origin || !url.pathname.startsWith(BASE)) return;
  const isPage = e.request.mode === 'navigate' || url.pathname.endsWith('.json');
  if (isPage) {
    // Network first so content stays fresh; fall back to cache offline.
    e.respondWith(fetch(e.request).then((res) => {
      const copy = res.clone();
      caches.open(RUNTIME).then((c) => c.put(e.request, copy));
      return res;
    }).catch(() => caches.match(e.request, { ignoreSearch: true }).then((r) => r || caches.match(BASE))));
    return;
  }
  e.respondWith(caches.match(e.request).then((hit) => hit || fetch(e.request).then((res) => {
    if (res.ok) { const copy = res.clone(); caches.open(RUNTIME).then((c) => c.put(e.request, copy)); }
    return res;
  })));
});
`;
fs.writeFileSync(path.join(dist, 'sw.js'), sw);
console.log(`Service worker: ${shell.length} files precached (version ${version}).`);
